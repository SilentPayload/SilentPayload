#!/usr/bin/env python3
"""Build the profile: generate every SVG asset, then write README.md.

    python3 scripts/build_folio.py
    python3 scripts/build_folio.py --check    build to a temp dir and diff

Single sources of truth are data/profile.json and data/repos.json. Nothing in
README.md should be edited by hand; this script owns it. Standard library only.
"""

import argparse
import json
import shutil
import sys
import tempfile
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from folio_theme import THEMES                      # noqa: E402
import folio_components as C                        # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def load():
    profile = json.loads((DATA / "profile.json").read_text(encoding="utf-8"))
    repos = json.loads((DATA / "repos.json").read_text(encoding="utf-8"))
    return profile, repos


def write_pair(out_dir, stem, builder):
    """Write stem-dark.svg and stem-light.svg from one builder."""
    for theme, pal in THEMES.items():
        path = out_dir / f"{stem}-{theme}.svg"
        path.write_text(builder(pal), encoding="utf-8")


def build_assets(out_dir, profile, repos):
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []

    write_pair(out_dir, "header", lambda pal: C.header(profile, pal))
    written.append("header")

    write_pair(out_dir, "figures", lambda pal: C.figures(profile["figures"], pal))
    written.append("figures")

    for section in repos["sections"]:
        stem = "label-" + section["title"].lower().replace(" ", "-")
        write_pair(out_dir, stem,
                   lambda pal, s=section: C.label(s["title"], s["meta"], pal))
        written.append(stem)

        for repo in section["repos"]:
            stem = "card-" + repo["slug"]
            write_pair(out_dir, stem, lambda pal, r=repo: C.card(r, pal))
            written.append(stem)

    return written


def picture(stem, alt, width=None, href=None):
    """A theme-aware image. GitHub honours prefers-color-scheme in <picture>."""
    w = f' width="{width}"' if width else ""
    img = (
        f'<picture>'
        f'<source media="(prefers-color-scheme: dark)" srcset="folio/{stem}-dark.svg">'
        f'<source media="(prefers-color-scheme: light)" srcset="folio/{stem}-light.svg">'
        f'<img alt="{alt}" src="folio/{stem}-light.svg"{w}>'
        f'</picture>'
    )
    return f'<a href="{href}">{img}</a>' if href else img


def build_readme(profile, repos):
    o = []
    o.append(picture("header", f'{profile["handle"]}. {profile["name"]}, {profile["tagline"]}'))
    o.append("")
    o.append(picture("figures", "Figures: " + ", ".join(
        f'{f["value"]} {f["label"]}' for f in profile["figures"])))
    o.append("")

    for section in repos["sections"]:
        stem = "label-" + section["title"].lower().replace(" ", "-")
        o.append(picture(stem, f'{section["title"]}: {section["meta"]}'))
        o.append("")

        row = [picture("card-" + r["slug"],
                       f'{r["name"]}. {r["blurb"]}',
                       href=r["url"])
               for r in section["repos"]]
        o.append("".join(row))
        o.append("")

        # the same links as plain text, so the section is usable without images
        o.append(" · ".join(f'[{r["name"]}]({r["url"]})' for r in section["repos"]))
        o.append("")

    o.append("---")
    o.append("")
    o.append(" · ".join(f'[{l["label"]}]({l["url"]})' for l in profile["links"]))
    o.append("")
    o.append(f'<sub>Generated by <code>scripts/build_folio.py</code> from '
             f'<code>data/</code> on {date.today().isoformat()}. '
             f'Do not edit this file by hand.</sub>')
    o.append("")
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="build to a temp dir and report whether the committed "
                         "output is stale, without writing anything")
    args = ap.parse_args()

    profile, repos = load()

    if args.check:
        tmp = Path(tempfile.mkdtemp())
        build_assets(tmp, profile, repos)
        readme = build_readme(profile, repos)
        stale = []
        for built in sorted(tmp.glob("*.svg")):
            live = ROOT / "folio" / built.name
            if not live.exists() or live.read_text(encoding="utf-8") != built.read_text(encoding="utf-8"):
                stale.append(f"folio/{built.name}")
        live_readme = ROOT / "README.md"
        if not live_readme.exists():
            stale.append("README.md")
        else:
            a = [l for l in live_readme.read_text(encoding="utf-8").splitlines()
                 if "Generated by" not in l]
            b = [l for l in readme.splitlines() if "Generated by" not in l]
            if a != b:
                stale.append("README.md")
        shutil.rmtree(tmp, ignore_errors=True)
        if stale:
            print("stale, re-run build_folio.py:")
            for s in stale:
                print(f"  {s}")
            return 1
        print("up to date")
        return 0

    written = build_assets(ROOT / "folio", profile, repos)
    (ROOT / "README.md").write_text(build_readme(profile, repos), encoding="utf-8")
    print(f"wrote {len(written) * 2} assets to folio/ and README.md")
    for w in written:
        print(f"  {w}-{{dark,light}}.svg")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
